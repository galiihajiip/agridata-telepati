#!/usr/bin/env python3
"""CLI entrypoint for the raw dataset forensic audit (Block 2).

Usage:
    python scripts/audit_dataset.py --dataset-root "<PATH>" [--output-dir artifacts/audit]

This script is READ-ONLY with respect to the dataset: it never modifies,
renames, or deletes anything under --dataset-root. It fails loudly (nonzero
exit code) when a JSON cannot be parsed, a required file is missing, or an
annotation references an unknown image ID, while still writing a full report
so the specific findings are visible rather than a bare crash.
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import asdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from agridata.dataset.inspect import SplitAudit, audit_split, detect_cross_split_overlap  # noqa: E402
from agridata.logging_utils import setup_logging  # noqa: E402

SPLITS = ("train", "valid", "test")
DEFAULT_ANNOTATION_FILENAME = "_annotations.coco.json"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Raw dataset forensic audit (read-only).")
    parser.add_argument(
        "--dataset-root",
        required=True,
        type=Path,
        help="Path to the dataset root containing train/valid/test split directories.",
    )
    parser.add_argument(
        "--output-dir",
        default=Path("artifacts/audit"),
        type=Path,
        help="Directory to write the machine- and human-readable audit reports to.",
    )
    parser.add_argument(
        "--annotation-filename",
        default=DEFAULT_ANNOTATION_FILENAME,
        help="Annotation JSON filename expected inside each split directory.",
    )
    return parser.parse_args()


def build_markdown_report(audits: dict[str, SplitAudit], overlap: dict) -> str:
    lines = [
        "# Raw Dataset Forensic Audit Report",
        "",
        "Generated by `scripts/audit_dataset.py`. This audit is READ-ONLY: no raw "
        "dataset file was modified, renamed, or deleted to produce it. No canonical "
        "class mapping has been applied yet (that is a separate, later step).",
        "",
    ]

    for split, audit in audits.items():
        lines.append(f"## Split: `{split}`")
        lines.append("")
        if not audit.exists:
            lines.append(f"**FATAL:** split directory or annotation file does not exist (`{audit.json_path}`).")
            lines.append("")
            continue
        if audit.parse_error:
            lines.append(f"**FATAL:** JSON parse error: {audit.parse_error}")
            lines.append("")
            continue

        lines += [
            f"- JSON path: `{audit.json_path}`",
            f"- Top-level keys: {audit.top_level_keys}",
            f"- Images: {audit.num_images}",
            f"- Annotations: {audit.num_annotations}",
            f"- Raw categories: {audit.num_categories}",
            "",
            "### Raw categories",
            "",
            "| id | name | supercategory |",
            "|---:|---|---|",
        ]
        for c in audit.categories:
            lines.append(f"| {c['id']} | {c['name']} | {c.get('supercategory')} |")
        lines.append("")

        fatal_bbox = [b for b in audit.bbox_issues if b.severity == "FATAL"]
        warn_bbox = [b for b in audit.bbox_issues if b.severity == "WARNING"]

        lines += [
            "### Integrity findings",
            "",
            f"- Categories with zero annotations: {len(audit.categories_zero_annotations)}"
            f" -> {[c['name'] for c in audit.categories_zero_annotations]}",
            f"- Images with zero annotations: {len(audit.images_zero_annotations)}",
            f"- Annotations referencing missing image IDs (FATAL): {len(audit.annotations_missing_image_ref)}",
            f"- Duplicate annotation IDs: {len(audit.duplicate_annotation_ids)}",
            f"- Duplicate image IDs: {len(audit.duplicate_image_ids)}",
            f"- Invalid bounding boxes (FATAL): {len(fatal_bbox)}",
            f"- Suspicious bounding boxes (WARNING): {len(warn_bbox)}",
            f"- Missing image files referenced by JSON (FATAL): {len(audit.missing_image_files)}",
            f"- Corrupt/unreadable images: {len(audit.corrupt_images)}",
            f"- Declared-vs-actual dimension mismatches: {len(audit.dimension_mismatches)}",
            f"- Image formats: {audit.image_formats}",
            "",
            f"**Split status: {'FATAL' if audit.is_fatal else 'OK (see warnings above)'}**",
            "",
        ]

    lines.append("## Cross-split overlap (data leakage check)")
    lines.append("")
    for key, names in overlap["filename_overlap"].items():
        lines.append(f"- Filename overlap {key}: {len(names)} shared filenames")
    for key, hashes in overlap["content_hash_overlap"].items():
        lines.append(f"- Exact content (md5) overlap {key}: {len(hashes)} shared files")
    for key, hashes in overlap["perceptual_hash_overlap"].items():
        lines.append(f"- Perceptual hash (aHash, exact-bucket) overlap {key}: {len(hashes)} candidate near-duplicates")
    lines += [
        "",
        "Note: perceptual-hash overlap is a best-effort exact-bucket aHash check, not "
        "a full nearest-neighbor Hamming-distance search. Treat any match as a "
        "candidate requiring visual confirmation, not proof of leakage.",
        "",
    ]

    return "\n".join(lines)


def main() -> int:
    setup_logging()
    args = parse_args()

    dataset_root: Path = args.dataset_root
    if not dataset_root.exists():
        print(f"FATAL: dataset root does not exist: {dataset_root}", file=sys.stderr)
        return 2

    audits: dict[str, SplitAudit] = {}
    for split in SPLITS:
        split_dir = dataset_root / split
        audits[split] = audit_split(split, split_dir, args.annotation_filename)

    overlap = detect_cross_split_overlap(audits)

    args.output_dir.mkdir(parents=True, exist_ok=True)

    json_report = {
        "dataset_root": str(dataset_root),
        "splits": {split: asdict(audit) for split, audit in audits.items()},
        "cross_split_overlap": overlap,
    }
    json_path = args.output_dir / "dataset_audit_report.json"
    with json_path.open("w", encoding="utf-8") as f:
        json.dump(json_report, f, indent=2, default=str)

    markdown = build_markdown_report(audits, overlap)
    md_path = args.output_dir / "dataset_audit_report.md"
    md_path.write_text(markdown, encoding="utf-8")

    print("\n" + markdown)
    print(f"\nJSON report written to: {json_path}")
    print(f"Markdown report written to: {md_path}")

    any_fatal = any(audit.is_fatal for audit in audits.values())
    if any_fatal:
        print("\nAUDIT RESULT: FATAL issues detected. See report for details.", file=sys.stderr)
        return 1

    print("\nAUDIT RESULT: PASS (no fatal issues; review warnings in report).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
